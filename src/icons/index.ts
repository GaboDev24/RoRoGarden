export type IconName = keyof typeof FA_ICONS

export interface IconOptions {
  size?: number | string
  className?: string
  ariaLabel?: string
}

/**
 * Crea un elemento SVGSVGElement de Font Awesome listo para insertar en el DOM.
 */
export function createFaIcon(name: IconName, options: IconOptions = {}): SVGSVGElement {
  const icon = FA_ICONS[name]
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg')

  const size = options.size ?? '1em'
  svg.setAttribute('viewBox', icon.viewBox)
  svg.setAttribute('width', typeof size === 'number' ? `${size}px` : size)
  svg.setAttribute('height', typeof size === 'number' ? `${size}px` : size)
  svg.setAttribute('fill', 'currentColor')

  if (options.className) {
    svg.setAttribute('class', `fa-icon ${options.className}`)
  } else {
    svg.setAttribute('class', 'fa-icon')
  }

  if (options.ariaLabel) {
    svg.setAttribute('role', 'img')
    svg.setAttribute('aria-label', options.ariaLabel)
  } else {
    svg.setAttribute('aria-hidden', 'true')
  }

  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path')
  path.setAttribute('d', icon.path)
  svg.appendChild(path)

  return svg
}

/**
 * Genera el string HTML del SVG de Font Awesome para uso inline.
 */
export function faIconHtml(name: IconName, options: IconOptions = {}): string {
  const icon = FA_ICONS[name]
  const size = options.size ?? '1em'
  const sizeAttr = typeof size === 'number' ? `${size}px` : size
  const cls = options.className ? `fa-icon ${options.className}` : 'fa-icon'
  const aria = options.ariaLabel
    ? `role="img" aria-label="${options.ariaLabel}"`
    : 'aria-hidden="true"'

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.viewBox}" width="${sizeAttr}" height="${sizeAttr}" fill="currentColor" class="${cls}" ${aria}><path d="${icon.path}"/></svg>`
}

